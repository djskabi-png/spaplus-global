async function createAd(input: Record<string, unknown>) {
  const key = clean(input.key) as MarketLanguage;
  if (!(key in CURRENT_ADS)) throw new Error("Invalid market/language key");
  const formId = clean(input.formId);
  const imageHash = clean(input.imageHash);
  const message = clean(input.message);
  const headline = clean(input.headline);
  const description = clean(input.description);
  const link = clean(input.link);
  if (!/^\d{10,30}$/.test(formId) || !/^[a-f0-9]{20,80}$/i.test(imageHash)) throw new Error("Invalid form or image");
  if (!message || !headline || !description || !/^https:\/\/app\.spaplus\.co\//.test(link)) throw new Error("Invalid creative copy");
  const oldAd = await graph(CURRENT_ADS[key], "GET", { fields: "id,name,adset_id" });
  const adsetId = clean(oldAd.adset_id);
  if (!/^\d{10,30}$/.test(adsetId)) throw new Error("Existing ad set was not found");
  const creative = await graph(`${AD_ACCOUNT_ID}/adcreatives`, "POST", {
    name: `SpaPlus Qualified V2 ${key} 2026-08-15`,
    object_story_spec: JSON.stringify({
      page_id: PAGE_ID,
      link_data: {
        link,
        message,
        name: headline,
        description,
        image_hash: imageHash,
        call_to_action: { type: "SIGN_UP", value: { lead_gen_form_id: formId } },
      },
    }),
  });
  const creativeId = clean(creative.id);
  if (!/^\d{10,30}$/.test(creativeId)) throw new Error("Creative was not created");
  const ad = await graph(`${AD_ACCOUNT_ID}/ads`, "POST", {
    name: `SpaPlus Qualified Spa Businesses V2 ${key} 2026-08-15`,
    adset_id: adsetId,
    creative: JSON.stringify({ creative_id: creativeId }),
    status: "ACTIVE",
  });
  return { key, oldAdId: CURRENT_ADS[key], adsetId, creativeId, adId: clean(ad.id) };
}

