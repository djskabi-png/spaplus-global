export async function POST(request: Request) {
  if (!authorized(request)) return Response.json({ error: "Unauthorized" }, { status: 401 });
  try {
    const body = (await request.json()) as { action?: string; input?: Record<string, unknown> };
    if (body.action === "inspect") return Response.json({ success: true, ...(await inspect()) });
    if (body.action === "create_form") {
      const key = clean(body.input?.key) as MarketLanguage;
      if (!(key in FORM_COPY)) throw new Error("Invalid form key");
      return Response.json({ success: true, key, result: await createForm(key) });
    }
    if (body.action === "upload_image") {
      const name = clean(body.input?.name);
      const bytes = clean(body.input?.bytes);
      if (!/^SPAPLUS_[A-Z_0-9-]+\.png$/.test(name) || bytes.length < 1000 || bytes.length > 12_000_000) throw new Error("Invalid image payload");
      return Response.json({ success: true, result: await graph(`${AD_ACCOUNT_ID}/adimages`, "POST", { name, bytes }) });
    }
    if (body.action === "create_ad") return Response.json({ success: true, result: await createAd(body.input || {}) });
    if (body.action === "pause_old_ads") {
      const results: Record<string, unknown> = {};
      for (const [key, adId] of Object.entries(CURRENT_ADS)) results[key] = await graph(adId, "POST", { status: "PAUSED" });
      return Response.json({ success: true, results });
    }
    if (body.action === "test_lead") return Response.json({ success: true, result: await testLead(body.input || {}) });
    throw new Error("Unsupported action");
  } catch (error: unknown) {
    console.error("Meta campaign admin action failed", { message: error instanceof Error ? error.message : "Unknown error" });
    return Response.json({ error: error instanceof Error ? error.message : "Meta campaign action failed" }, { status: 503 });
  }
}
