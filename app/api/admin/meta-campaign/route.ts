function clean(value: unknown) {
  return String(value ?? "").trim();
}

function constantTimeEqual(left: string, right: string) {
  const a = new TextEncoder().encode(left);
  const b = new TextEncoder().encode(right);
  const length = Math.max(a.length, b.length);
  let mismatch = a.length ^ b.length;
  for (let index = 0; index < length; index += 1) {
    mismatch |= (a[index] || 0) ^ (b[index] || 0);
  }
  return mismatch === 0;
}

function authorized(request: Request) {
  const expected = setting("META_CAMPAIGN_ADMIN_TOKEN");
  const provided = request.headers.get("x-spaplus-campaign-token") || "";
  return expected.length >= 48 && constantTimeEqual(expected, provided);
}

function pageToken() {
  const token = setting("META_PAGE_ACCESS_TOKEN")
    .replace(/^\uFEFF/, "")
    .trim()
    .replace(/^["']|["']$/g, "");
  if (!token) throw new Error("Meta access token is not configured");
  return token;
}

async function graph(
  path: string,
  method: "GET" | "POST" = "GET",
  params: Record<string, string> = {},
) {
  const url = new URL(`https://graph.facebook.com/${GRAPH_VERSION}/${path.replace(/^\//, "")}`);
  const body = new URLSearchParams({ ...params, access_token: pageToken() });
  if (method === "GET") {
    for (const [key, value] of body) url.searchParams.set(key, value);
    const getResponse = await fetch(url, { headers: { accept: "application/json" } });
    const payload = await getResponse.json().catch(() => ({}));
    if (!getResponse.ok) throw new Error(`Meta GET ${path} failed (${getResponse.status}): ${JSON.stringify(payload).slice(0, 700)}`);
    return payload as Record<string, unknown>;
  }
  const response = await fetch(url, {
    method,
    headers: { "content-type": "application/x-www-form-urlencoded" },
    body,
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(`Meta POST ${path} failed (${response.status}): ${JSON.stringify(payload).slice(0, 700)}`);
  return payload as Record<string, unknown>;
}

