function applyLocale(nextLocale) {
  locale = nextLocale === "he" ? "he" : "en";
  const t = copy[locale];
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "he" ? "rtl" : "ltr";
  document.title = t.pageTitle;
  document.querySelector('meta[name="description"]').content = t.pageDescription;
  document.querySelectorAll("[data-copy]").forEach((element) => {
    const value = t[element.dataset.copy];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-aria-copy]").forEach((element) => {
    const value = t[element.dataset.ariaCopy];
    if (value) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("a.brand").forEach((element) => {
    element.setAttribute("aria-label", t.homeLabel);
  });
  document.querySelector("#cookie-banner-title").textContent = t.cookieTitle;
  document.querySelector("#cookie-banner-description-text").textContent = t.cookieBody;
  cookieEssentialButton.textContent = t.cookieEssentialOnly;
  cookieAllButton.textContent = t.cookieAcceptAll;
  cookieSettingsButton.textContent = t.cookieSettings;
  languageSelect.value = locale;
  const isHebrewPath =
    /\/country-partners\/he\/?$/.test(location.pathname) ||
    /\/he\/country-partners\/?$/.test(location.pathname);
  const canonicalUrl = locale === "he"
    ? "https://djskabi-png.github.io/spaplus-global/country-partners/he/"
    : "https://djskabi-png.github.io/spaplus-global/country-partners/";
  const mainSitePrefix = isHebrewPath ? "../../" : "../";
  document.querySelector('link[rel="canonical"]').href = canonicalUrl;
  document.querySelector('meta[property="og:title"]').content = t.pageTitle;
  document.querySelector('meta[property="og:description"]').content = t.pageDescription;
  document.querySelector('meta[property="og:url"]').content = canonicalUrl;
  document.querySelector(".back-link").href = mainSitePrefix + "?lang=" + locale;
  document.querySelectorAll("a.brand").forEach((link) => {
    link.href = mainSitePrefix + "?lang=" + locale;
  });
  document.querySelectorAll(".privacy-link").forEach((link) => {
    link.href = mainSitePrefix + "?lang=" + locale + "#privacy";
  });
  if (!isHebrewPath && locale === "he" && !new URLSearchParams(location.search).has("preview")) {
    location.replace("./he/");
  }
}

